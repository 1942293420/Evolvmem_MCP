const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const {startFixture}=require('./project_modules_fixture.cjs');
(async()=>{
  const fixture=await startFixture();
  const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_EXECUTABLE||undefined});
  const page=await browser.newPage({viewport:{width:1440,height:1050}});page.setDefaultTimeout(5000);
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  try {
    await page.goto(fixture.base);
    await page.waitForSelector('[data-module-card="mod_orders"]');
    assert.match(await page.locator('[data-project-event="2"]').innerText(),/历史来源已变更|不计入当前摘要/);
    await page.locator('[data-project-event="2"]').click();
    assert.match(await page.locator('[data-project-event="2"]').innerText(),/原文.*不可|来源.*不可/);
    assert.equal(await page.locator('[data-project-event="2"] script').count(),0);
    await page.locator('[data-module-new]').click();
    await page.locator('[data-module-form] [name=name]').fill('库存 <img src=x onerror="window.injected=1">');
    await page.locator('[data-module-form] [name=aliases]').fill('库存核对, 仓储');
    await page.locator('[data-module-form] [name=description]').fill('按项目管理库存。');
    await page.locator('[data-module-form] button[type=submit]').click();
    await page.waitForSelector('[data-module-card="mod_created1"]');
    assert.equal(await page.locator('[data-module-card="mod_created1"] img').count(),0);
    await page.locator('[data-module-card="mod_created1"] [data-module-edit]').click();
    await page.locator('[data-module-form] [name=name]').fill('库存管理');
    fixture.state.conflict=true;
    await page.locator('[data-module-form] button[type=submit]').click();
    await page.waitForFunction(()=>document.querySelector('[data-module-notice]')?.textContent.includes('最新'));
    assert.equal(await page.locator('[data-module-form] [name=name]').inputValue(),'库存管理','CAS must retain draft');
    await page.locator('[data-module-form] button[type=submit]').click();
    await page.waitForFunction(()=>document.querySelector('[data-module-card="mod_created1"]')?.textContent.includes('库存管理'));
    await page.locator('[data-module-card="mod_created1"] [data-module-state]').click();
    await page.waitForFunction(()=>document.querySelector('[data-module-card="mod_created1"]')?.textContent.includes('已停用'));
    await page.locator('[data-module-card="mod_suggested"] [data-module-state]').click();
    await page.waitForFunction(()=>document.querySelector('[data-module-card="mod_suggested"]')?.textContent.includes('使用中'));
    await page.waitForSelector('[data-memory-module-form]');
    await page.locator('[data-module-original]').evaluate(el=>{el.focus();el.setSelectionRange(0,15);});
    await page.locator('[data-use-module-quote]').click();
    const quote=await page.locator('[data-module-quote]').inputValue();assert.ok(quote&&fixture.state.quote.includes(quote));
    await page.locator('[data-module-target]').selectOption('mod_orders');
    await page.locator('[data-memory-module-form] button[type=submit]').click();
    await page.waitForSelector('[data-memory-module="mod_orders"]');
    assert.match(await page.locator('#memory').innerText(),/待审核|仅作归类/);
    await page.locator('[data-memory-module="mod_orders"] [data-module-remove]').click();
    await page.waitForFunction(()=>!document.querySelector('[data-memory-module="mod_orders"]'));
    assert.equal(fixture.state.bindings[0].status,'inactive');
    // A removed binding is restored with its actual revision, never an assumed zero.
    await page.locator('[data-module-original]').evaluate(el=>el.setSelectionRange(0,10));
    await page.locator('[data-use-module-quote]').click();
    await page.locator('[data-memory-module-form] button[type=submit]').click();
    await page.waitForSelector('[data-memory-module="mod_orders"]');
    assert.equal(fixture.state.writes.at(-1).body.expected_revision,2);
    await page.locator('[data-module-card="mod_orders"] [data-module-state]').click();
    await page.waitForFunction(()=>!document.querySelector('[data-memory-module="mod_orders"]'));
    await page.locator('[data-module-card="mod_orders"] [data-module-state]').click();
    await page.waitForSelector('[data-memory-module="mod_orders"]');
    fixture.state.conflict=true;
    await page.locator('[data-memory-module="mod_orders"] [data-module-remove]').click();
    await page.waitForFunction(()=>document.querySelector('[data-memory-module-notice]')?.textContent.includes('最新'));
    assert.equal(await page.locator('[data-memory-module="mod_orders"]').count(),1,'CAS must not remove optimistically');
    await page.locator('[data-memory-module="mod_orders"] [data-module-remove]').click();
    await page.waitForFunction(()=>!document.querySelector('[data-memory-module="mod_orders"]'));
    assert.equal(fixture.state.writes.at(-1).body.expected_revision,4);
    // Reuse/remount retains the module draft and does not repeat a browsing GET.
    await page.locator('[data-module-original]').evaluate(el=>el.setSelectionRange(0,10));
    await page.locator('[data-use-module-quote]').click();
    const gets=fixture.state.gets.filter(p=>p.endsWith('/memory/1')).length;
    const draft=await page.locator('[data-module-quote]').inputValue();
    await page.evaluate(()=>EvolvMemModules.mountMemory(document.querySelector('#memory'),1));
    assert.equal(await page.locator('[data-module-quote]').inputValue(),draft);
    assert.equal(fixture.state.gets.filter(p=>p.endsWith('/memory/1')).length,gets);
    if(process.env.EVOLVMEM_SCREENSHOT_DIR){fs.mkdirSync(process.env.EVOLVMEM_SCREENSHOT_DIR,{recursive:true});await page.screenshot({path:path.join(process.env.EVOLVMEM_SCREENSHOT_DIR,'project-modules-detail.png'),fullPage:true});}
    const beforeRevoked=fixture.state.writes.length;
    await page.evaluate(()=>{EvolvAuth.canWrite=false;document.querySelector('[data-module-card="mod_orders"] [data-module-state]').click();});
    assert.equal(fixture.state.writes.length,beforeRevoked,'Event handlers must recheck permission');
    await page.locator('[data-project-back]').click();
    assert.match(await page.locator('[data-project-card="alpha"]').innerText(),/当前.*1.*历史.*2|有效.*1.*历史.*2/);
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2));
    if(process.env.EVOLVMEM_SCREENSHOT_DIR){fs.mkdirSync(process.env.EVOLVMEM_SCREENSHOT_DIR,{recursive:true});await page.screenshot({path:path.join(process.env.EVOLVMEM_SCREENSHOT_DIR,'project-modules-desktop.png'),fullPage:true});}
    const writes=fixture.state.writes.length;
    await page.goto(fixture.base+'/?readonly=1');
    await page.waitForSelector('[data-module-card="mod_orders"]');
    assert.equal(await page.locator('[data-module-new],[data-module-edit],[data-module-state],[data-memory-module-form],[data-module-remove]').count(),0);
    assert.equal(fixture.state.writes.length,writes);
    assert.equal(await page.evaluate(()=>window.injected),undefined);
    fixture.state.modules.splice(0);
    await page.goto(fixture.base);
    await page.waitForFunction(()=>document.querySelector('[data-project-modules]')?.textContent.includes('尚未划分业务模块'));
    assert.equal(await page.locator('[data-module-card]').count(),0,'An empty registry must stay empty');
    assert.equal(fixture.state.writes.length,writes);
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({passed:true,checks:['desktop CRUD and CAS','source quote selection','binding removal revisions','pending and historical badges','same-mount draft/cache','readonly no writes','escaped text'],writes}));
  } finally {await browser.close();await fixture.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
