-- Runtime archive capture, CAS payload refs, continuity, context subsets, and cutover audit tables.
CREATE EXTENSION IF NOT EXISTS vector;
CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE SCHEMA IF NOT EXISTS em_runtime;

CREATE TABLE IF NOT EXISTS em_runtime.schema_migrations (
    version integer PRIMARY KEY,
    migration_name text NOT NULL UNIQUE,
    applied_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE IF NOT EXISTS em_runtime.session_archives (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project text NOT NULL,
    adapter text NOT NULL,
    external_session_id text NOT NULL,
    payload_path text NOT NULL DEFAULT '',
    payload_sha256 text NOT NULL,
    state text NOT NULL DEFAULT 'available',
    expires_at text NOT NULL DEFAULT '',
    purged_at text,
    created_at text NOT NULL,
    device_id text NOT NULL DEFAULT '',
    cas_blob_sha256 text NOT NULL DEFAULT '',
    UNIQUE (adapter, external_session_id)
);

CREATE TABLE IF NOT EXISTS em_runtime.session_archive_storage (
    archive_id bigint PRIMARY KEY REFERENCES em_runtime.session_archives(id) ON DELETE CASCADE,
    manifest_sha256 text NOT NULL,
    content_sha256 text NOT NULL,
    logical_bytes bigint NOT NULL
);

CREATE TABLE IF NOT EXISTS em_runtime.session_archive_holds (
    archive_id bigint NOT NULL REFERENCES em_runtime.session_archives(id) ON DELETE CASCADE,
    source_context_id bigint NOT NULL,
    reason text NOT NULL,
    created_at text NOT NULL,
    PRIMARY KEY (archive_id, source_context_id)
);

CREATE TABLE IF NOT EXISTS em_runtime.archive_source_exclusions (
    archive_id bigint PRIMARY KEY REFERENCES em_runtime.session_archives(id) ON DELETE CASCADE,
    payload_sha256 text NOT NULL,
    reason text NOT NULL,
    verified_at text NOT NULL
);

CREATE TABLE IF NOT EXISTS em_runtime.conversation_history (
    archive_id bigint PRIMARY KEY REFERENCES em_runtime.session_archives(id) ON DELETE CASCADE,
    messages text NOT NULL DEFAULT '[]',
    body text NOT NULL DEFAULT '',
    content_hash text NOT NULL DEFAULT '',
    cleaned_at text NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS em_runtime.lan_session_uploads (
    device_id text NOT NULL,
    session_id text NOT NULL,
    sha256 text NOT NULL,
    project text NOT NULL DEFAULT '',
    declared_project text NOT NULL DEFAULT '',
    attribution_reason text NOT NULL DEFAULT '',
    received_at double precision NOT NULL,
    backfill_status text NOT NULL DEFAULT 'pending',
    backfill_result text NOT NULL DEFAULT '{}',
    total_bytes bigint NOT NULL DEFAULT 0,
    received_bytes bigint NOT NULL DEFAULT 0,
    archive_id bigint,
    extraction_status text NOT NULL DEFAULT 'not_requested',
    extraction_result text NOT NULL DEFAULT '{}',
    error text NOT NULL DEFAULT '',
    source_order bigint,
    extracted_at text,
    source_format text NOT NULL DEFAULT 'codex-jsonl',
    PRIMARY KEY (device_id, session_id, sha256)
);

CREATE TABLE IF NOT EXISTS em_runtime.lan_session_heads (
    device_id text NOT NULL,
    session_id text NOT NULL,
    sha256 text,
    source_order bigint,
    PRIMARY KEY (device_id, session_id)
);

CREATE TABLE IF NOT EXISTS em_runtime.lan_session_backfills (
    device_id text NOT NULL,
    session_id text NOT NULL,
    applied_revision bigint NOT NULL DEFAULT 0,
    workstream_id text NOT NULL DEFAULT '',
    PRIMARY KEY (device_id, session_id)
);

CREATE TABLE IF NOT EXISTS em_runtime.lan_write_requests (
    user_id text NOT NULL,
    tool text NOT NULL,
    request_id text NOT NULL,
    payload_hash text NOT NULL,
    result text,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (user_id, tool, request_id)
);

CREATE TABLE IF NOT EXISTS em_runtime.lan_workspace_bindings (
    remote_key text PRIMARY KEY,
    fingerprint text NOT NULL,
    workstream_id text NOT NULL
);

CREATE TABLE IF NOT EXISTS em_runtime.lan_memory_revision (
    id integer PRIMARY KEY CHECK (id = 1),
    revision bigint NOT NULL
);

CREATE TABLE IF NOT EXISTS em_runtime.local_capture_files (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id text NOT NULL,
    path text NOT NULL,
    device bigint NOT NULL DEFAULT 0,
    inode bigint NOT NULL DEFAULT 0,
    scanned_offset_bytes bigint NOT NULL DEFAULT 0,
    scanned_line bigint NOT NULL DEFAULT 0,
    pending_bytes bigint NOT NULL DEFAULT 0,
    since_floor double precision NOT NULL DEFAULT 0,
    file_size bigint NOT NULL DEFAULT 0,
    file_mtime double precision NOT NULL DEFAULT 0,
    anchor_offset bigint NOT NULL DEFAULT 0,
    anchor_bytes bigint NOT NULL DEFAULT 0,
    anchor_sha256 text NOT NULL DEFAULT '',
    file_state text NOT NULL DEFAULT 'advancing',
    blocked_cap_bytes bigint NOT NULL DEFAULT 0,
    archived_offset_bytes bigint NOT NULL DEFAULT 0,
    archived_line bigint NOT NULL DEFAULT 0,
    archived_batches bigint NOT NULL DEFAULT 0,
    archived_events bigint NOT NULL DEFAULT 0,
    filtered_events bigint NOT NULL DEFAULT 0,
    failed_batches bigint NOT NULL DEFAULT 0,
    rewrite_count bigint NOT NULL DEFAULT 0,
    last_error text NOT NULL DEFAULT '',
    last_success_at text NOT NULL DEFAULT '',
    last_error_at text NOT NULL DEFAULT '',
    first_seen_at text NOT NULL DEFAULT '',
    updated_at text NOT NULL DEFAULT '',
    UNIQUE (device, inode)
);

CREATE TABLE IF NOT EXISTS em_runtime.local_capture_scans (
    id integer PRIMARY KEY CHECK (id = 1),
    last_scan_at text NOT NULL DEFAULT '',
    last_success_at text NOT NULL DEFAULT '',
    last_error text NOT NULL DEFAULT '',
    scans bigint NOT NULL DEFAULT 0,
    scanned_bytes bigint NOT NULL DEFAULT 0,
    archived_batches bigint NOT NULL DEFAULT 0,
    archived_events bigint NOT NULL DEFAULT 0,
    filtered_events bigint NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS em_runtime.context_project_registry (
    project text PRIMARY KEY,
    status text NOT NULL DEFAULT 'active',
    revision bigint NOT NULL DEFAULT 1,
    created_at text NOT NULL DEFAULT '',
    updated_at text NOT NULL DEFAULT '',
    display_name text NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS em_runtime.context_project_aliases (
    alias text PRIMARY KEY,
    project text NOT NULL,
    revision bigint NOT NULL DEFAULT 1,
    created_at text NOT NULL DEFAULT '',
    updated_at text NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS em_runtime.context_project_workspace_bindings (
    workspace_fingerprint text NOT NULL,
    project text NOT NULL,
    state text NOT NULL DEFAULT 'candidate',
    is_default integer NOT NULL DEFAULT 0,
    method text NOT NULL DEFAULT '',
    revision bigint NOT NULL DEFAULT 1,
    created_at text NOT NULL DEFAULT '',
    updated_at text NOT NULL DEFAULT '',
    PRIMARY KEY (workspace_fingerprint, project)
);

CREATE TABLE IF NOT EXISTS em_runtime.context_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identity_key text NOT NULL,
    content_type text NOT NULL,
    project text NOT NULL DEFAULT '',
    scope text NOT NULL DEFAULT 'project',
    status text NOT NULL DEFAULT 'candidate',
    tier text NOT NULL DEFAULT 'normal',
    tags text NOT NULL DEFAULT '',
    importance double precision NOT NULL DEFAULT 5.0,
    confidence double precision NOT NULL DEFAULT 0.5,
    source_state text NOT NULL DEFAULT 'none',
    source_count integer NOT NULL DEFAULT 0,
    success_count integer NOT NULL DEFAULT 0,
    failure_count integer NOT NULL DEFAULT 0,
    access_count integer NOT NULL DEFAULT 0,
    last_accessed text,
    last_verified_at text,
    expires_at text,
    supersedes bigint,
    superseded_by bigint,
    created_at text NOT NULL,
    updated_at text NOT NULL,
    experience_payload text NOT NULL DEFAULT '',
    effective_from text,
    effective_until text,
    occurred_at text,
    mentioned_at text,
    projects text NOT NULL DEFAULT '[]',
    personal_general integer NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS em_runtime.context_layers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id bigint NOT NULL REFERENCES em_runtime.context_items(id) ON DELETE CASCADE,
    layer text NOT NULL CHECK (layer IN ('l0', 'l1', 'l2')),
    content text NOT NULL,
    content_hash text NOT NULL,
    generator text NOT NULL DEFAULT '',
    created_at text NOT NULL,
    updated_at text NOT NULL,
    search_tsv tsvector GENERATED ALWAYS AS (to_tsvector('simple', coalesce(content, ''))) STORED,
    embedding vector(768),
    UNIQUE (item_id, layer)
);

CREATE TABLE IF NOT EXISTS em_runtime.context_project_resolutions (
    item_id bigint PRIMARY KEY REFERENCES em_runtime.context_items(id) ON DELETE CASCADE,
    resolution_state text NOT NULL,
    decision_source text NOT NULL DEFAULT 'none',
    review_state text NOT NULL DEFAULT 'not_required',
    proposed_project text NOT NULL DEFAULT '',
    resolved_project text NOT NULL DEFAULT '',
    confidence text NOT NULL DEFAULT 'none',
    method text NOT NULL DEFAULT '',
    evidence_json text NOT NULL DEFAULT '[]',
    resolver_version text NOT NULL DEFAULT '',
    revision bigint NOT NULL DEFAULT 1,
    reviewed_at text,
    created_at text NOT NULL DEFAULT '',
    updated_at text NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS em_runtime.context_sources (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id bigint NOT NULL REFERENCES em_runtime.context_items(id) ON DELETE CASCADE,
    archive_id bigint,
    source_kind text NOT NULL,
    source_ref text NOT NULL DEFAULT '',
    extraction_version text NOT NULL DEFAULT '',
    created_at text NOT NULL DEFAULT '',
    UNIQUE (item_id, source_kind, source_ref)
);

CREATE TABLE IF NOT EXISTS em_runtime.lan_publications (
    context_id bigint PRIMARY KEY REFERENCES em_runtime.context_items(id) ON DELETE CASCADE,
    author text NOT NULL,
    active integer NOT NULL DEFAULT 1,
    title text NOT NULL DEFAULT '',
    summary text NOT NULL DEFAULT '',
    project text NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS em_runtime.continuity_workstreams (
    id text PRIMARY KEY,
    project text NOT NULL,
    workspace_fingerprint text NOT NULL,
    parent_id text,
    current_context_id bigint NOT NULL,
    checkpoint_revision bigint NOT NULL,
    state_version bigint NOT NULL,
    status text NOT NULL CHECK (status IN ('open','paused','blocked','completed','cancelled')),
    repo_kind text NOT NULL DEFAULT 'non_git' CHECK (repo_kind IN ('git','non_git')),
    repo_branch text NOT NULL DEFAULT '',
    repo_root_commit text NOT NULL DEFAULT '',
    repo_head_commit text NOT NULL DEFAULT '',
    created_at text NOT NULL,
    updated_at text NOT NULL,
    completed_at text
);

CREATE TABLE IF NOT EXISTS em_runtime.continuity_focus (
    project text NOT NULL,
    workspace_fingerprint text NOT NULL,
    workstream_id text REFERENCES em_runtime.continuity_workstreams(id),
    revision bigint NOT NULL DEFAULT 0,
    updated_at text NOT NULL,
    PRIMARY KEY (project, workspace_fingerprint)
);

CREATE TABLE IF NOT EXISTS em_runtime.continuity_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workstream_id text,
    event_type text NOT NULL,
    before_revision bigint,
    after_revision bigint,
    before_state_version bigint,
    after_state_version bigint,
    error_code text NOT NULL DEFAULT '',
    created_at text NOT NULL
);

CREATE TABLE IF NOT EXISTS em_runtime.task_history_grants (
    request_id text PRIMARY KEY,
    identity_hash text UNIQUE NOT NULL,
    archive_id bigint NOT NULL,
    source_sha256 text NOT NULL,
    source_revision text NOT NULL,
    project text NOT NULL,
    source_format text NOT NULL,
    task_id bigint,
    state text NOT NULL,
    result text,
    created_at double precision NOT NULL
);

CREATE TABLE IF NOT EXISTS em_runtime.migration_checkpoints (
    source_db text NOT NULL,
    table_name text NOT NULL,
    snapshot_sha256 text NOT NULL,
    target_db text NOT NULL,
    last_key text NOT NULL DEFAULT '',
    rows_imported bigint NOT NULL DEFAULT 0,
    completed boolean NOT NULL DEFAULT false,
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (source_db, table_name, target_db)
);

CREATE TABLE IF NOT EXISTS em_runtime.cutover_write_journal (
    seq bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    library_key text NOT NULL,
    request_id text NOT NULL,
    actor_id text NOT NULL DEFAULT '',
    op_type text NOT NULL,
    target_table text NOT NULL,
    target_key text NOT NULL,
    payload jsonb NOT NULL,
    replayed_to_sqlite boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (library_key, request_id, op_type, target_key)
);

CREATE INDEX IF NOT EXISTS idx_em_rt_archives_proj_state ON em_runtime.session_archives (project, state);
CREATE INDEX IF NOT EXISTS idx_em_rt_uploads_dev ON em_runtime.lan_session_uploads (device_id, session_id);
CREATE INDEX IF NOT EXISTS idx_em_rt_layers_tsv ON em_runtime.context_layers USING gin (search_tsv);
CREATE INDEX IF NOT EXISTS idx_em_rt_layers_hnsw ON em_runtime.context_layers USING hnsw (embedding vector_cosine_ops) WITH (m = 16, ef_construction = 64) WHERE embedding IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_em_rt_ctx_identity ON em_runtime.context_items (identity_key);
CREATE INDEX IF NOT EXISTS idx_em_rt_uploads_archive ON em_runtime.lan_session_uploads (archive_id);
CREATE INDEX IF NOT EXISTS idx_em_rt_journal_replay ON em_runtime.cutover_write_journal (library_key, replayed_to_sqlite, seq);
CREATE INDEX IF NOT EXISTS idx_em_rt_ws_proj ON em_runtime.continuity_workstreams (project, status);

INSERT INTO em_runtime.schema_migrations (version, migration_name)
VALUES (1, '002_runtime_capture_and_continuity')
ON CONFLICT (version) DO NOTHING;
