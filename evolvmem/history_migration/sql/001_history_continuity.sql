\set ON_ERROR_STOP on
-- Private quarantined legacy migration; formal targets require a bound operator lease.
-- psql variables: database_name owner_role library_id route_epoch policy_epoch
--                 parent_run_id parent_manifest_sha256
BEGIN;
SET LOCAL statement_timeout='3000ms'; SET LOCAL lock_timeout='300ms';
SELECT set_config('history.continuity_database', :'database_name', true);
SELECT set_config('history.continuity_owner', :'owner_role', true);
SELECT set_config('history.continuity_library', :'library_id', true);
SELECT set_config('history.continuity_route', :'route_epoch', true);
SELECT set_config('history.continuity_policy', :'policy_epoch', true);
SELECT set_config('history.continuity_parent', :'parent_run_id', true);
SELECT set_config('history.continuity_parent_hash', :'parent_manifest_sha256', true);
DO $gate$
DECLARE t text;
BEGIN
 IF current_database() !~ '^em_pilot_[a-z0-9_]+$' THEN
   PERFORM em_security.assert_history_operator_binding();
 END IF;
 PERFORM 1 FROM em_security.library_state WHERE singleton FOR UPDATE;
 IF current_database()<>current_setting('history.continuity_database')
 OR current_user<>current_setting('history.continuity_owner')
 OR NOT EXISTS(SELECT 1 FROM pg_roles r JOIN pg_database d ON d.datdba=r.oid
   WHERE r.rolname=current_user AND d.datname=current_database() AND NOT r.rolcanlogin
   AND NOT r.rolsuper AND NOT r.rolbypassrls AND NOT r.rolcreatedb AND NOT r.rolcreaterole)
 OR (SELECT count(*) FROM em_security.library_state WHERE singleton AND library_id=current_setting('history.continuity_library')::uuid
   AND kind='legacy' AND device_id IS NULL AND project_id IS NULL AND authority_state='pg_staging' AND acl_state='updating'
   AND route_epoch=current_setting('history.continuity_route')::bigint AND policy_epoch=current_setting('history.continuity_policy')::bigint)<>1
 THEN RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='history_continuity_precondition'; END IF;
 -- Only the verified core is the B6 parent. No source/organization dependency.
 FOREACH t IN ARRAY ARRAY['context_project_registry','memories','context_items','context_layers',
   'legacy_memory_migrations','context_project_resolutions','history_schema_migrations','history_import_runs',
   'history_import_chunks','history_import_links','history_batch_schema_migrations','history_batch_progress'] LOOP
   EXECUTE format('LOCK TABLE em_content.%I IN ACCESS EXCLUSIVE MODE',t);
   IF NOT EXISTS(SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname='em_content'
     AND c.relname=t AND c.relowner=current_user::regrole AND c.relrowsecurity AND c.relforcerowsecurity)
   THEN RAISE EXCEPTION 'history_continuity_parent_owner_rls_required'; END IF;
 END LOOP;
 IF (SELECT count(*) FROM em_content.history_batch_schema_migrations WHERE version=1
   AND migration_name='001_history_bounded_chain' AND library_id=current_setting('history.continuity_library')::uuid)<>1
 OR (SELECT count(*) FROM em_content.history_import_runs r JOIN em_content.history_batch_progress p USING(run_id)
   WHERE r.run_id=current_setting('history.continuity_parent')::uuid AND r.library_id=current_setting('history.continuity_library')::uuid
   AND p.manifest_hash=current_setting('history.continuity_parent_hash') AND r.state='core_verified'
   AND p.stage='verified' AND p.generation=p.verify_generation
   AND r.manifest->'source'->'source'->>'namespace' IN ('owner','kane','public'))<>1
 THEN RAISE EXCEPTION 'history_continuity_verified_parent_required'; END IF;
END;
$gate$;

